"""Independent host KATs using Python cryptography; no legacy source input."""
from pathlib import Path
import hashlib, hmac
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives import serialization
key=bytes(range(16))
nonce=bytes(range(12))
payload=bytes.fromhex('0a050a030a0101')
vin=b'5YJ3E1EA7KF000001'
challenge=bytes(range(16))
info=b'\x08\x07\x12\x03\x04\x05\x06'
def tlv(tag,value): return bytes([tag,len(value)])+value
session=tlv(0,b'\x06')+tlv(2,vin)+tlv(6,challenge)+b'\xff'+info
subkey=hmac.digest(key,b'session info','sha256')
session_hmac=hmac.digest(subkey,session,'sha256')
# Response domain=3, received counter=1 (not outbound counter=8).
request_hash=b'\x05'+bytes(range(16))
response=tlv(0,b'\x09')+tlv(1,b'\x03')+tlv(2,vin)+tlv(5,(1).to_bytes(4,'big'))+tlv(7,(1).to_bytes(4,'big'))+tlv(8,request_hash)+tlv(9,bytes(4))+b'\xff'
aad=hashlib.sha256(response).digest()
sealed=AESGCM(key).encrypt(nonce,payload,aad)
values=dict(key=key,nonce=nonce,payload=payload,vin=vin,challenge=challenge,info=info,session_hmac=session_hmac,request_hash=request_hash,aad=aad,ciphertext=sealed[:-16],tag=sealed[-16:])
vcsec_response=response.replace(tlv(1,b'\x03'),tlv(1,b'\x02'),1)
vcsec_aad=hashlib.sha256(vcsec_response).digest()
vcsec_sealed=AESGCM(key).encrypt(nonce,payload,vcsec_aad)
values.update(vcsec_aad=vcsec_aad,vcsec_ciphertext=vcsec_sealed[:-16],vcsec_tag=vcsec_sealed[-16:])
local_key=ec.derive_private_key(1,ec.SECP256R1())
remote_key=ec.derive_private_key(2,ec.SECP256R1())
remote_public=remote_key.public_key().public_bytes(serialization.Encoding.X962,serialization.PublicFormat.UncompressedPoint)
session_key=hashlib.sha1(local_key.exchange(ec.ECDH(),remote_key.public_key())).digest()[:16]
encoded_info=b'\x08\x07\x12\x41'+remote_public+b'\x1a\x10'+bytes(range(16))+b'\x25'+(1234).to_bytes(4,'little')
def sign_info(encoded):
    transcript=tlv(0,b'\x06')+tlv(2,vin)+tlv(6,challenge)+b'\xff'+encoded
    return hmac.digest(hmac.digest(session_key,b'session info','sha256'),transcript,'sha256')
denied_info=encoded_info+b'\x28\x01'
values.update(session_key=session_key,encoded_info=encoded_info,info_tag=sign_info(encoded_info),denied_info=denied_info,denied_tag=sign_info(denied_info))
text='// SPDX-License-Identifier: Apache-2.0\n// Generated by make_vectors.py, not production code. Fixed PUBLIC test data.\n#pragma once\nnamespace vectors {\n'
for name,value in values.items(): text+=f'inline constexpr unsigned char {name}[]={{'+','.join(f'0x{x:02x}' for x in value)+'};\n'
text+='}\n'
p=Path(__file__).with_name('vectors.hpp')
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / 'tools'))
from bench_confinement import preflight
preflight(files=(p,)).revalidate()
# Regeneration must be byte-identical unless test fixtures were intentionally changed.
if p.exists(): assert p.read_text()==text, 'vector drift'
else: p.write_text(text)
print('Independent HMAC/GCM response fixtures generated/verified')
